import type { LevelId } from "@/lib/levels";
import type { Question } from "@/lib/quests";

export type Theme = "village" | "market" | "port" | "peaks";

export type Npc = {
  id: string;
  name: string;
  color: string; // HEX, т.к. рисуем на canvas
  x: number;
  y: number; // уровень, на котором стоит житель (ноги)
  lines: string[]; // что говорит перед заданием
  after: string; // что говорит, если с ним заговорить снова
  question: Question;
};

export type Platform = { x: number; y: number; w: number }; // можно запрыгнуть снизу
export type Block = { x: number; y: number; w: number; h: number }; // сплошной блок

export type Chapter = {
  id: string;
  land: string;
  level: LevelId;
  order: number;
  xp: number;
  title: string;
  theme: Theme;
  intro: string[];
  outro: string[];
  width: number;
  goalX: number;
  platforms: Platform[];
  blocks: Block[];
  npcs: Npc[];
};

type Layout = {
  width: number;
  goalX: number;
  platforms: Platform[];
  blocks: Block[];
  slots: { x: number; y: number }[];
};

type Meta = Pick<
  Chapter,
  "id" | "level" | "order" | "xp" | "title" | "theme" | "intro" | "outro"
>;

type NpcDef = Omit<Npc, "id" | "x" | "y">;

function make(meta: Meta, layout: Layout, defs: NpcDef[]): Chapter {
  return {
    ...meta,
    land: "english",
    width: layout.width,
    goalX: layout.goalX,
    platforms: layout.platforms,
    blocks: layout.blocks,
    npcs: defs.map((d, i) => ({
      ...d,
      id: `${meta.id}-${i}`,
      x: layout.slots[i].x,
      y: layout.slots[i].y,
    })),
  };
}

