/* ---------- Настройки помощника (хранятся в браузере) ---------- */

export type Prefs = {
  enabled: boolean; // показывать помощника
  greeted: boolean; // уже встретил человека
  tips: boolean; // всплывающие подсказки
};

export const DEFAULT_PREFS: Prefs = { enabled: true, greeted: false, tips: true };

const KEY = "questlands-assistant";

export function loadPrefs(): Prefs {
  try {
    const raw = localStorage.getItem(KEY);
    if (raw) return { ...DEFAULT_PREFS, ...(JSON.parse(raw) as Partial<Prefs>) };
  } catch {
    /* хранилище недоступно */
  }
  return DEFAULT_PREFS;
}

export function savePrefs(p: Prefs) {
  try {
    localStorage.setItem(KEY, JSON.stringify(p));
  } catch {
    /* хранилище недоступно */
  }
}

/* ---------- Где сейчас человек ---------- */

export type PageKind =
  | "home"
  | "dashboard"
  | "english"
  | "code"
  | "quest"
  | "vocab"
  | "terminal"
  | "other";

export function pageKindOf(pathname: string): PageKind {
  if (pathname === "/") return "home";
  if (pathname.startsWith("/dashboard")) return "dashboard";
  if (pathname.startsWith("/vocab")) return "vocab";
  if (pathname.startsWith("/terminal")) return "terminal";
  if (pathname.startsWith("/quest/")) {
    const id = pathname.slice("/quest/".length);
    if (id.startsWith("english")) return "english";
    if (id.startsWith("code")) return "code";
    return "quest";
  }
  return "other";
}

// В английском и коде открывается игровой мир (с героем и жителями)
export const isGameKind = (k: PageKind) => k === "english" || k === "code";

