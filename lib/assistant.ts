export function localAnswer(question: string, kind: PageKind): string {
  const hit = RULES.find((r) => r.re.test(question));
  if (hit) return hit.answer;
  const hint = TIPS[kind][0];
  return `Тут я могу ответить только на вопросы про игру. Попробуй спросить про управление, жизни, опыт или ранги. ${hint}`;
}
