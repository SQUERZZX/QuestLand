// Подсказки, зависящие от прогресса героя
export function tipsFor(kind: PageKind, save: SaveData): string[] {
  const out = [...TIPS[kind]];
  if (kind === "dashboard") {
    if (save.hero.lives < MAX_LIVES) {
      out.unshift(
        `У героя осталось жизней: ${save.hero.lives} из ${MAX_LIVES}. Не пропускай дни, чтобы не терять новые.`,
      );
    }
    if (save.hero.streak >= 2) {
      out.unshift(`Серия уже ${save.hero.streak} дн. подряд. Так держать!`);
    }
  }
  if (kind === "vocab" && save.vocab.length === 0) {
    out.unshift("Словарь пока пуст. Слова появятся, когда пройдёшь главу английского.");
  }
  return out;
}

