import { LAYOUT_A, LAYOUT_B, make } from "@/lib/chapterKit";
import type { Chapter, Meta, NpcDef } from "@/lib/chapterKit";

/*
  Лес кода: те же миры и тот же движок, что и у английского.
  Учим JavaScript, потому что его можно запускать прямо в терминале в браузере.
  Сюжет: Туман Багов стёр у жителей синтаксис.

  Строка жителя:
  [имя, цвет, реплика 1, реплика 2, реплика после ответа,
   вопрос, верный ответ, неверный 1, неверный 2, неверный 3, объяснение]
  Позиция верного ответа считается автоматически, чтобы ответы не лежали всегда на одном месте.
*/

type Row = [
  string, string, string, string, string,
  string, string, string, string, string, string,
];

